#!/usr/bin/env bash

set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
web_root="$repo_root/Platforms/Web"
baseline="$web_root/api/public.d.ts"
mode="${1:-check}"

if [[ "$mode" != "check" && "$mode" != "--update" ]]; then
    echo "Usage: $0 [--update]" >&2
    exit 64
fi

npm --prefix "$web_root" run build >/dev/null

snapshot="$(mktemp "${TMPDIR:-/tmp}/innonetwork-web-api.XXXXXX")"
trap 'rm -f "$snapshot"' EXIT

{
    echo "// InnoNetwork Web declaration API"
    echo "// Generated by Scripts/check_web_public_api.sh --update"
    while IFS= read -r declaration; do
        relative_path="${declaration#"$web_root/dist/"}"
        echo
        echo "// --- $relative_path ---"
        cat "$declaration"
    done < <(find "$web_root/dist" -type f -name '*.d.ts' -print | LC_ALL=C sort)
} >"$snapshot"

if [[ "$mode" == "--update" ]]; then
    mkdir -p "$(dirname "$baseline")"
    cp "$snapshot" "$baseline"
    echo "Updated Platforms/Web/api/public.d.ts"
    exit 0
fi

if [[ ! -f "$baseline" ]]; then
    echo "Missing Web declaration API baseline." >&2
    echo "Run Scripts/check_web_public_api.sh --update after reviewing the API." >&2
    exit 1
fi

if ! diff -u "$baseline" "$snapshot"; then
    echo "Web declaration API changed." >&2
    echo "Review compatibility, then update the baseline explicitly if intentional." >&2
    exit 1
fi

echo "Web declaration API baseline: OK"
