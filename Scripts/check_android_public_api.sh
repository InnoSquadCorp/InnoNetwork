#!/usr/bin/env bash

set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
api_dir="$repo_root/Platforms/Android/api"
mode="${1:-check}"

if [[ "$mode" != "check" && "$mode" != "--update" ]]; then
    echo "Usage: $0 [--update]" >&2
    exit 64
fi

if ! command -v javap >/dev/null 2>&1; then
    echo "Android public API verification requires javap from a JDK." >&2
    exit 1
fi

work_dir="$(mktemp -d "${TMPDIR:-/tmp}/innonetwork-android-api.XXXXXX")"
trap 'rm -rf "$work_dir"' EXIT

"$repo_root/Platforms/Android/gradlew" \
    -p "$repo_root/Platforms/Android" \
    :innonetwork:bundleReleaseAar \
    :innonetwork-client:bundleReleaseAar \
    :innonetwork-kotlinx-serialization:bundleReleaseAar \
    :innonetwork-ksp:jar >/dev/null

snapshot_jar() {
    local module="$1"
    local jar_path="$2"
    local output="$work_dir/$module.api"

    {
        echo "# InnoNetwork Android JVM API: $module"
        echo "# Generated by Scripts/check_android_public_api.sh --update"
        while IFS= read -r class_file; do
            case "$class_file" in
                */R.class|*/R\$*.class|*/BuildConfig.class|module-info.class)
                    continue
                    ;;
            esac
            class_name="${class_file%.class}"
            class_name="${class_name//\//.}"
            class_api="$work_dir/current-class.api"
            javap -classpath "$jar_path" -public -s -constants "$class_name" >"$class_api"
            if ! grep -Eq '^public (.* )?(class|interface|enum) ' "$class_api"; then
                continue
            fi
            echo
            echo "## $class_name"
            cat "$class_api"
        done < <(jar tf "$jar_path" | LC_ALL=C sort | grep '\.class$')
    } >"$output"

    if [[ "$mode" == "--update" ]]; then
        mkdir -p "$api_dir"
        cp "$output" "$api_dir/$module.api"
        echo "Updated Platforms/Android/api/$module.api"
        return
    fi

    if [[ ! -f "$api_dir/$module.api" ]]; then
        echo "Missing Android API baseline: Platforms/Android/api/$module.api" >&2
        echo "Run Scripts/check_android_public_api.sh --update after reviewing the API." >&2
        exit 1
    fi
    if ! diff -u "$api_dir/$module.api" "$output"; then
        echo "Android public API changed for $module." >&2
        echo "Review compatibility, then update the baseline explicitly if intentional." >&2
        exit 1
    fi
}

snapshot_aar() {
    local module="$1"
    local aar_path="$2"
    local classes_jar="$work_dir/$module-classes.jar"

    unzip -p "$aar_path" classes.jar >"$classes_jar"
    snapshot_jar "$module" "$classes_jar"
}

snapshot_aar \
    "innonetwork" \
    "$repo_root/Platforms/Android/innonetwork/build/outputs/aar/innonetwork-release.aar"
snapshot_aar \
    "innonetwork-client" \
    "$repo_root/Platforms/Android/innonetwork-client/build/outputs/aar/innonetwork-client-release.aar"
snapshot_aar \
    "innonetwork-kotlinx-serialization" \
    "$repo_root/Platforms/Android/innonetwork-kotlinx-serialization/build/outputs/aar/innonetwork-kotlinx-serialization-release.aar"

ksp_jar="$(find "$repo_root/Platforms/Android/innonetwork-ksp/build/libs" \
    -maxdepth 1 -type f -name 'innonetwork-ksp-*.jar' \
    ! -name '*sources*' ! -name '*javadoc*' -print)"
if [[ -z "$ksp_jar" || "$ksp_jar" == *$'\n'* ]]; then
    echo "Expected exactly one InnoNetwork KSP binary JAR." >&2
    exit 1
fi
snapshot_jar "innonetwork-ksp" "$ksp_jar"

if [[ "$mode" == "check" ]]; then
    echo "Android public API baselines: OK"
fi
