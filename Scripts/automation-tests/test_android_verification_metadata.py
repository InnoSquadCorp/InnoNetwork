"""Human-run regeneration helpers for the strict Android verification files."""
import hashlib
import importlib.util
from pathlib import Path
import unittest

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location('verification', ROOT / 'Scripts/android_verification_metadata.py')
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)

VERSION = '9.5.0-16666295'
JARS = {host: f'aapt2 {host} jar'.encode() for host in m.HOSTS}
METADATA = ROOT / 'Platforms/Android/gradle/verification-metadata.xml'
CONSUMER = ROOT / 'SmokeTests/AndroidConsumer/gradle/verification-metadata.xml'


def artifact(name, value):
    return (f'\n         <artifact name="{name}">'
            f'\n            <sha256 value="{value}" origin="Generated by Gradle"/>'
            f'\n         </artifact>')


def document(*hosts, version=VERSION):
    aapt2 = ''.join(artifact(f'aapt2-{version}-{host}.jar', hashlib.sha256(JARS[host]).hexdigest()) for host in hosts)
    return ('<?xml version="1.0" encoding="UTF-8"?>\n<verification-metadata>\n   <configuration>\n'
            '      <verify-metadata>true</verify-metadata>\n      <verify-signatures>false</verify-signatures>\n'
            '      <trusted-artifacts>\n         <trust group="com.innosquad.innonetwork" reason="first party"/>\n'
            '      </trusted-artifacts>\n   </configuration>\n   <components>\n'
            f'      <component group="com.android.tools.build" name="aapt2" version="{version}">'
            f'{aapt2}{artifact(f"aapt2-{version}.pom", "1" * 64)}\n      </component>\n'
            '      <component group="com.squareup.okhttp3" name="okhttp" version="5.5.1">'
            f'{artifact("okhttp-5.5.1.jar", "2" * 64)}\n      </component>\n'
            '   </components>\n</verification-metadata>\n')


class GoogleMaven:
    def __init__(self, sha1=None):
        self.urls, self.sha1 = [], sha1

    def __call__(self, url):
        self.urls.append(url)
        prefix = f'https://dl.google.com/android/maven2/com/android/tools/build/aapt2/{VERSION}/aapt2-{VERSION}-'
        assert url.startswith(prefix), url
        host, suffix = url.removeprefix(prefix).split('.jar')
        if suffix == '.sha1':
            return (self.sha1 or hashlib.sha1(JARS[host]).hexdigest()).encode()
        assert suffix == '', url
        return JARS[host]


class AndroidVerificationMetadataTests(unittest.TestCase):
    def test_committed_files_stay_strict_and_list_every_aapt2_host(self):
        for path in (METADATA, CONSUMER):
            with self.subTest(path=path.name):
                m.check(path.read_text())

    def test_clear_keeps_configuration_and_drops_every_component(self):
        cleared = m.clear(document('osx'))
        self.assertIn('<verify-metadata>true</verify-metadata>', cleared)
        self.assertIn('<trust group="com.innosquad.innonetwork"', cleared)
        self.assertNotIn('<component ', cleared)
        self.assertIn('<components>\n   </components>', cleared)
        with self.assertRaisesRegex(ValueError, 'no components'):
            m.check(cleared)

    def test_lenient_or_ambiguous_metadata_is_never_rewritten(self):
        for text in (document('osx').replace('<verify-metadata>true', '<verify-metadata>false'),
                     document('osx').replace('</components>', '</components>\n   <components/>')):
            with self.subTest(text=text[-80:]):
                for operation in (m.clear, m.check, lambda value: m.add_aapt2_platforms(value, GoogleMaven())):
                    with self.assertRaises(ValueError):
                        operation(text)

    def test_missing_hosts_are_added_in_gradle_order_and_downloaded_once(self):
        maven, cache = GoogleMaven(), {}
        first = m.add_aapt2_platforms(document('osx'), maven, cache)
        second = m.add_aapt2_platforms(document('osx'), maven, cache)
        self.assertEqual(first, second)
        self.assertEqual(len(maven.urls), 4, 'linux and windows jars and their SHA-1 files, once')
        names = [line.split('"')[1] for line in first.splitlines() if '<artifact name=' in line]
        self.assertEqual(names, [f'aapt2-{VERSION}-linux.jar', f'aapt2-{VERSION}-osx.jar',
                                 f'aapt2-{VERSION}-windows.jar', f'aapt2-{VERSION}.pom', 'okhttp-5.5.1.jar'])
        for host in ('linux', 'windows'):
            self.assertIn(f'<sha256 value="{hashlib.sha256(JARS[host]).hexdigest()}" origin="{m.AAPT2_ORIGIN}"/>', first)
        m.check(first)
        self.assertEqual(m.add_aapt2_platforms(first, GoogleMaven()), first)
        with self.assertRaisesRegex(ValueError, 'missing host jars: linux, windows'):
            m.check(document('osx'))

    def test_unverifiable_or_unexpected_aapt2_input_fails_closed(self):
        with self.assertRaisesRegex(ValueError, 'published SHA-1'):
            m.add_aapt2_platforms(document('linux'), GoogleMaven(sha1='0' * 40))
        with self.assertRaisesRegex(ValueError, 'resolved no host jar'):
            m.add_aapt2_platforms(document(), GoogleMaven())
        for version in ('9.5.0', '9.5.0-1/../../evil', '9.5.0-16666295?x'):
            with self.subTest(version=version), self.assertRaisesRegex(ValueError, 'unexpected aapt2 version'):
                m.add_aapt2_platforms(document(version=version), GoogleMaven())


if __name__ == '__main__':
    unittest.main()
