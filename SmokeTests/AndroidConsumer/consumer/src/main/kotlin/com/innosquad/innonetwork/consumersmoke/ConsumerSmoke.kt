package com.innosquad.innonetwork.consumersmoke

import com.innosquad.innonetwork.StreamingNetworkSession
import com.innosquad.innonetwork.client.NetworkClient
import com.innosquad.innonetwork.client.codegen.InnoBody
import com.innosquad.innonetwork.client.codegen.InnoEndpoint
import com.innosquad.innonetwork.client.codegen.InnoHeader
import com.innosquad.innonetwork.client.codegen.InnoHttpMethod
import com.innosquad.innonetwork.client.codegen.InnoPath
import com.innosquad.innonetwork.client.codegen.InnoQuery
import com.innosquad.innonetwork.serialization.decodeJson
import kotlinx.serialization.builtins.serializer
import okhttp3.Request
import okhttp3.RequestBody
import okhttp3.MultipartBody

/** Endpoint whose native OkHttp adapter is generated by the published KSP artifact. */
@InnoEndpoint(method = InnoHttpMethod.GET, path = "/messages/{pathSegment}")
public data class MessageEndpoint public constructor(
    @InnoPath public val pathSegment: String,
    @InnoQuery("locale") public val locale: String?,
    @InnoHeader("X-Request-ID") public val requestID: String,
)

/** Exercises generated native request-body forwarding without a converter runtime. */
@InnoEndpoint(method = InnoHttpMethod.POST, path = "/messages")
public data class CreateMessageEndpoint public constructor(
    @InnoBody public val body: RequestBody,
)

/** Exercises OkHttp-compatible custom method generation with an intentional empty body. */
@InnoEndpoint(method = "REPORT", path = "/reports")
public class ReportEndpoint

/** Concrete native RequestBody subtypes use the same generated execution boundary. */
@InnoEndpoint(method = InnoHttpMethod.POST, path = "/multipart")
public data class MultipartEndpoint public constructor(
    @InnoBody public val body: MultipartBody,
)

/** Compile-only proof that the published modules expose every Android 1.0 layer. */
public class ConsumerSmoke public constructor(
    private val client: NetworkClient,
    private val streamingSession: StreamingNetworkSession,
) {
    /** Executes a generated definition through the optional JSON adapter. */
    public suspend fun loadMessage(pathSegment: String): String {
        val endpoint = MessageEndpoint(
            pathSegment = pathSegment,
            locale = "ko-KR",
            requestID = "consumer-smoke",
        )
        return client.request(endpoint.apiDefinition { response ->
            response.decodeJson(String.serializer())
        })
    }

    /** Opens a caller-owned native streaming response without buffering the complete body. */
    public suspend fun loadFirstLine(url: String): String? {
        val request = Request.Builder().url(url).build()
        return streamingSession.open(request).use { response ->
            response.source.readUtf8Line()
        }
    }
}
